// Zero-width characters for binary steganography
const ZW_SPACE = '\u200B'; // 0
const ZW_NON_JOINER = '\u200C'; // 1
const ZW_JOINER = '\u200D'; // separator

/**
 * Encodes an identifier (e.g. user email or studio signature) into invisible zero-width characters.
 */
export function encodeSteganographicWatermark(text: string, identifier: string): string {
  const binary = Array.from(identifier)
    .map((char) => char.charCodeAt(0).toString(2).padStart(8, '0'))
    .join('');

  const zeroWidthEncoded = Array.from(binary)
    .map((bit) => (bit === '0' ? ZW_SPACE : ZW_NON_JOINER))
    .join('');

  // Inject at first sentence boundary or at start
  const firstPeriod = text.indexOf('.');
  if (firstPeriod !== -1) {
    return text.slice(0, firstPeriod + 1) + ZW_JOINER + zeroWidthEncoded + ZW_JOINER + text.slice(firstPeriod + 1);
  }
  return ZW_JOINER + zeroWidthEncoded + ZW_JOINER + text;
}

/**
 * Decodes invisible zero-width watermark back to string identifier.
 */
export function decodeSteganographicWatermark(text: string): string | null {
  const parts = text.split(ZW_JOINER);
  if (parts.length < 3) return null;
  const encoded = parts[1];

  let binary = '';
  for (const char of encoded) {
    if (char === ZW_SPACE) binary += '0';
    else if (char === ZW_NON_JOINER) binary += '1';
  }

  if (binary.length % 8 !== 0) return null;

  let decoded = '';
  for (let i = 0; i < binary.length; i += 8) {
    const byte = binary.slice(i, i + 8);
    decoded += String.fromCharCode(parseInt(byte, 2));
  }
  return decoded;
}

